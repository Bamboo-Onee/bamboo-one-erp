"""Interfaces abstratas de Repositório (Ports) da camada de Domínio.

Seguem o Princípio da Inversão de Dependência (DIP) usando typing.Protocol.
"""

from typing import List, Optional, Protocol
from src.modules.cadastros_mestres.domain.entities.product import Product
from src.modules.cadastros_mestres.domain.entities.customer import Customer
from src.modules.cadastros_mestres.domain.entities.vehicle import Vehicle


class ProductRepositoryInterface(Protocol):
    async def create(self, product: Product) -> Product: ...
    async def get_by_sku(self, sku: str) -> Optional[Product]: ...
    async def list_all(self) -> List[Product]: ...
    async def delete(self, product_id: int) -> bool: ...


class CustomerRepositoryInterface(Protocol):
    async def create(self, customer: Customer) -> Customer: ...
    async def get_by_document(self, document: str) -> Optional[Customer]: ...
    async def list_all(self) -> List[Customer]: ...
    async def delete(self, customer_id: int) -> bool: ...


class VehicleRepositoryInterface(Protocol):
    async def create(self, vehicle: Vehicle) -> Vehicle: ...
    async def get_by_plate(self, plate: str) -> Optional[Vehicle]: ...
    async def list_all(self) -> List[Vehicle]: ...
    async def delete(self, vehicle_id: int) -> bool: ...
